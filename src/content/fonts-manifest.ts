/** One downloadable woff2 file (latin subset). */
export interface FontFile {
  readonly weight: number;
  /** Public path under /fonts. */
  readonly file: string;
  readonly bytes: number;
}

export interface FontManifestEntry {
  readonly family: string;
  readonly slug: string;
  readonly role: string;
  readonly weights: readonly number[];
  readonly files: readonly FontFile[];
  readonly license: string;
  /** Public path of the license text shipped beside the font files. */
  readonly licenseFile: string;
  readonly licenseBytes: number;
  readonly googleUrl: string;
  /** Where the woff2 files were taken from. */
  readonly source: string;
  readonly brands: readonly BrandId[];
  readonly note: string;
}

