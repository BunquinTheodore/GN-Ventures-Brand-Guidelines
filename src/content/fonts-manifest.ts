export function getFontFamily(slug: string): FontManifestEntry | undefined {
  return FONTS_MANIFEST.find((f) => f.slug === slug);
}

export function fontsForBrand(brand: BrandId): readonly FontManifestEntry[] {
  return FONTS_MANIFEST.filter((f) => f.brands.includes(brand));
}

